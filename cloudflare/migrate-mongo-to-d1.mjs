import fs from "node:fs/promises";
import process from "node:process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MongoClient } from "mongodb";

const uri = String(process.env.MONGO_URI || "").trim();
if (!uri) throw new Error("MONGO_URI is required.");

const databaseName = String(process.env.MONGO_DB_NAME || "wordzap");
const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const outputPath = String(process.env.D1_MIGRATION_SQL || path.join(scriptDir, "generated-migration.sql"));

function sql(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "0";
  if (typeof value === "boolean") return value ? "1" : "0";
  return "'" + String(value).replaceAll("'", "''") + "'";
}

function millis(value, fallback = Date.now()) {
  if (!value) return fallback;
  const date = value instanceof Date ? value : new Date(value);
  const n = date.getTime();
  return Number.isFinite(n) ? n : fallback;
}

function string(value, fallback = "") {
  return value === null || value === undefined ? fallback : String(value);
}

function json(value, fallback = []) {
  try { return JSON.stringify(value ?? fallback); }
  catch { return JSON.stringify(fallback); }
}

function rows(value) { return Array.isArray(value) ? value : []; }

function statement(table, columns, values, conflict = "") {
  return (
    "INSERT INTO " + table + "(" + columns.join(",") + ") VALUES(" +
    values.map(sql).join(",") + ")" +
    (conflict ? " " + conflict : "") + ";\n"
  );
}

const client = new MongoClient(uri, {
  connectTimeoutMS: 15000,
  serverSelectionTimeoutMS: 15000
});

await client.connect();
const db = client.db(databaseName);

const [profiles, languages, devices] = await Promise.all([
  db.collection("profileschemas").find({}).toArray(),
  db.collection("languagesschemas").find({}).toArray(),
  db.collection("devices").find({}).toArray().catch(() => [])
]);

let out = [
  "-- Generated by cloudflare/migrate-mongo-to-d1.mjs",
  "-- Source database: " + databaseName,
  "PRAGMA foreign_keys = ON;",
  "BEGIN TRANSACTION;",
  ""
].join("\n");

let profileCount = 0;
for (const profile of profiles) {
  const uniqe = string(profile.uniqe).trim();
  if (!uniqe) continue;
  const created = millis(profile.createdAt);
  const updated = millis(profile.updatedAt, created);
  out += statement(
    "profiles",
    ["uniqe","email","name","gender","language","created_at","updated_at"],
    [
      uniqe,
      string(profile.email),
      string(profile.name),
      string(profile.gender),
      string(profile.language || "en").toLowerCase(),
      created,
      updated
    ],
    "ON CONFLICT(uniqe) DO UPDATE SET " +
      "email=excluded.email,name=excluded.name,gender=excluded.gender," +
      "language=excluded.language,updated_at=excluded.updated_at"
  );
  profileCount += 1;
}

let dayMemberCount = 0;
let difficultyWordCount = 0;
let memberWordCount = 0;
let premiumCount = 0;

for (const languageDoc of languages) {
  const language = string(languageDoc.value || "en").toLowerCase();
  const docCreated = millis(languageDoc.createdAt);

  for (const premium of rows(languageDoc.premium)) {
    const uniqe = string(premium.uniqe).trim();
    if (!uniqe) continue;
    const updated = millis(languageDoc.updatedAt, docCreated);
    out += statement(
      "premium_scores",
      ["language","uniqe","name","premium_score","created_at","updated_at"],
      [language,uniqe,string(premium.name),Number(premium.premiumScore || 0),docCreated,updated],
      "ON CONFLICT(language,uniqe) DO UPDATE SET " +
        "name=excluded.name,premium_score=excluded.premium_score,updated_at=excluded.updated_at"
    );
    premiumCount += 1;
  }

  for (const day of rows(languageDoc.days)) {
    const dayKey = string(day.value).trim();
    if (!dayKey) continue;

    for (const difficulty of rows(day.difficulties)) {
      const difficultyValue = string(difficulty.value).trim();
      if (!difficultyValue) continue;

      rows(difficulty.words).forEach((word, index) => {
        const value = string(word).trim();
        if (!value) return;
        out += statement(
          "difficulty_words",
          ["day_key","language","difficulty","word_index","value","created_at"],
          [dayKey,language,difficultyValue,index,value,docCreated],
          "ON CONFLICT(day_key,language,difficulty,word_index) DO UPDATE SET value=excluded.value"
        );
        difficultyWordCount += 1;
      });

      for (const member of rows(difficulty.members)) {
        const uniqe = string(member.uniqe).trim();
        if (!uniqe) continue;
        const name = string(member.name);
        out += statement(
          "daily_members",
          ["day_key","language","difficulty","uniqe","name","total_score","created_at","updated_at"],
          [dayKey,language,difficultyValue,uniqe,name,Number(member.totalScore || 0),docCreated,millis(languageDoc.updatedAt,docCreated)],
          "ON CONFLICT(day_key,language,difficulty,uniqe) DO UPDATE SET " +
            "name=excluded.name,total_score=excluded.total_score,updated_at=excluded.updated_at"
        );
        dayMemberCount += 1;

        rows(member.words).forEach((word, index) => {
          const value = string(word?.value).trim();
          if (!value) return;
          out += statement(
            "member_words",
            ["day_key","language","difficulty","uniqe","word_index","value","guesswork_json","done","created_at","updated_at"],
            [
              dayKey,
              language,
              difficultyValue,
              uniqe,
              index,
              value,
              json(rows(word?.guesswork)),
              Boolean(word?.done),
              docCreated,
              millis(languageDoc.updatedAt,docCreated)
            ],
            "ON CONFLICT(day_key,language,difficulty,uniqe,word_index) DO UPDATE SET " +
              "value=excluded.value,guesswork_json=excluded.guesswork_json,done=excluded.done,updated_at=excluded.updated_at"
          );
          memberWordCount += 1;
        });
      }
    }
  }
}

let deviceCount = 0;
for (const device of devices) {
  const token = string(device.token).trim();
  const uniqe = string(device.uniqe).trim();
  if (!token || !uniqe) continue;
  const created = millis(device.createdAt);
  const updated = millis(device.updatedAt, created);
  out += statement(
    "device_tokens",
    ["token","uniqe","environment","bundle_id","created_at","updated_at"],
    [
      token,
      uniqe,
      ["sandbox","prod"].includes(device.environment) ? device.environment : "prod",
      string(device.bundleId || process.env.APP_BUNDLE_ID || "com.barak.wordzap"),
      created,
      updated
    ],
    "ON CONFLICT(token) DO UPDATE SET " +
      "uniqe=excluded.uniqe,environment=excluded.environment,bundle_id=excluded.bundle_id,updated_at=excluded.updated_at"
  );
  deviceCount += 1;
}

out += "\nCOMMIT;\n";
await fs.writeFile(outputPath, out, {mode:0o600});

console.log(JSON.stringify({
  ok:true,
  outputPath,
  profiles:profileCount,
  dailyMembers:dayMemberCount,
  difficultyWords:difficultyWordCount,
  memberWords:memberWordCount,
  premiumScores:premiumCount,
  deviceTokens:deviceCount
}, null, 2));

await client.close();
